#include <bits/stdc++.h>

using namespace std;

int main() {
    int t; cin >> t;
    while (t-- > 0) {
        int n, m, x, y;
        cin >> n >> m >> x >> y;

        int aux;
        for (int i = 0; i < n; i++) cin >> aux;
        for (int i = 0; i < m; i++) cin >> aux;

        cout << n+m << endl;
    }

    return 0;
}